// `docs/16` §3 里的「不配机械判据」豁免 —— 写它要付的那三样，是**可机械核的**
//
// 来历（M2d 定向复评 N1）：这条规矩本身是 M2d 立的（`docs/16` §3 开头那条
// 「『不配机械判据』不是一句可以白写的话」）。它规定：写一条「这一条不配机械判据」
// 要付三样——① 拒绝写的那条判据长什么样、② 它打不红的那一刀、③ 什么会让答案改变。
//
// **而它当时把自己也标成了一条没有机械判据的规矩**，给的理由是
// 「没有任何测试能检查『加条目的人读了它』」。
//
// ⚠️ **那个理由超范围了，这是本文件存在的全部原因。**
// 「测不了他**读**没读」与「测不了他**付**没付那三样」是两件事：
// 前者确实不留产物；**后者恰恰留产物**——`docs/16` §3 里一条新的豁免裁定，
// 旁边缺 ①②③，就在文件里躺着，扫得到。
//
// 复评把它写出来并且测过：在 BASE `959fa36` 上**红 1 条**——当时的 §3.9
// 写着「裁定：这一条不配机械判据，而这个理由本身要写下来」，底下是一段说理，
// **三样一个没有**；在 `ceda901` 上绿。**已知违规样本现成躺在 git 历史里**，
// 下面那条锚用的就是它的逐字原文。
//
// **可写、可红、有现成的已知违规样本——那就不该豁免。**
// `docs/16` §3 开头那段的末尾已经改掉，它自己不再是一条豁免。
//
// ⚠️ **这次犯的错与 M2d 的 F1 同形，一起记在这里**：F1 那次是
// 「错的归类被立成了『防止这种错归类』那条判据的范例」（`docs/17` §5.6 /
// `docs/11` §5.20 二）；这次是「一条规矩把自己排除在它自己的要求之外」。
// **两次都是写下了一个判断而没有去验它。**
//
// 写法仿 `tests/plugin-name-sync.test.mjs`（「两个源头必须保持一致」的独立小文件）：
// 抽取器写成本文件内的具名函数，**主判据与锚共用同一份**
// （`docs/16` §3.2：锚要钉在判据真正进入 assert 的那一层）。
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const read = (p) => readFileSync(new URL(`../${p}`, import.meta.url), 'utf8')
const DOCS16 = 'docs/16-M2b-裁定记录.md'

// 豁免的标志词。用**松的**这一个（不要求「裁定：」前缀），因为 BASE 上那两条的写法
// 并不一致：§3.9 写的是「**裁定：这一条不配机械判据……**」，§3.10 写的是
// 「这一条同样**不配机械判据**，理由与……」——**后者没有「裁定：」三个字**。
// 按前缀去认，会漏掉整整一种写法。
const EXEMPTION = '不配机械判据'

// 三样在正文里的形状：`**① …**` / `**② …**` / `**③ …**`。
const PAID = ['**①', '**②', '**③']

// 只扫**编号过的** §3.N 小节。两处有意排除在外：
//   · §3 开头那条规矩自己（无编号小节）——它必须反复提到这个词才能把规矩说清楚；
//   · §6「这份文档怎么用」里那条指路。
// 两处都是**谈论**这个词，不是**下**这条裁定。
function numberedSections(text) {
  const lines = text.split(/\r?\n/)
  const out = []
  let cur = null
  for (const line of lines) {
    if (/^###\s/.test(line)) {
      if (cur) out.push(cur)
      cur = /^###\s+3\.\d+/.test(line) ? { heading: line.trim(), body: [] } : null
      continue
    }
    if (/^##\s/.test(line)) {
      if (cur) out.push(cur)
      cur = null
      continue
    }
    if (cur) cur.body.push(line)
  }
  if (cur) out.push(cur)
  return out.map((s) => ({ heading: s.heading, body: s.body.join('\n') }))
}

// 主判据与三条锚**共用这一份**：返回「声明了豁免、却没付清三样」的小节，
// 每条附上它缺了哪几样。
function unpaidExemptions(text) {
  return numberedSections(text)
    .filter((s) => s.body.includes(EXEMPTION))
    .map((s) => ({ heading: s.heading, missing: PAID.filter((m) => !s.body.includes(m)) }))
    .filter((s) => s.missing.length > 0)
}

// ——— M3b 追加轮：把上面那条判据**核不到的那个情形**变成不可能发生 ———
//
// 上面那条按**小节**收、不按**裁定**收，于是一个小节里的第二条豁免可以**白嫖**第一条
// 付的三样（下面「盖不住的那一半」② 记着这件事）。M3b 把它从预测变成了实测：
// 往 §3.9 注入第二条「不配机械判据」而不付三样，**本文件当时一条都不红**。
//
// **修法不是把抽取器改成「按裁定收」**：那要判断散落的 ①②③ 归属哪一条豁免，
// 脆，而且会把一条老实的判据改成猜的（`docs/16` §3.2：锚要钉在判据真正迭代的那一层，
// 不是钉在一个更像那回事的层）。
// **改成限制每节至多一条**：这一刀**不假装**判据能按裁定核，它让那个核不到的情形
// **不可能发生**——要加第二条豁免，只能另起一节（那一节自己要付三样，上面那条就管得着），
// 或者真的把抽取器扩成按裁定收。
//
// 与上面那条**共用 `numberedSections()`**，不另起一份切块规则：那正是本仓库
// `hooks/lib/path-norm.mjs` 头部记着的那一族（两份逐字相同的实现真的分叉过）。
function multipleExemptions(text) {
  return numberedSections(text)
    .map((s) => ({ heading: s.heading, count: s.body.split(EXEMPTION).length - 1 }))
    .filter((s) => s.count > 1)
}

// BASE `959fa36` 上 §3.9 那条豁免的**逐字原文**（只取到说理结束，够判定了）。
// 它是这条判据的已知违规样本：声明了豁免，三样一个没付。
