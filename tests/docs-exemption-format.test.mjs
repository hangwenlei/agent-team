// ⭐ 已知违规样本锚：G2 那一刀的逐字形状——一个**三样付齐**的小节里塞进第二条豁免。
// 这正是 M3b 实测出「一条都不红」的那份输入，它是这条新判据存在的全部理由。
// ⚠️ 这份夹具必须**三样齐**：三样不齐的话上面那条老判据也会红，
// 那时这一条的红就证明不了「第二条豁免被抓住了」——它可能只是搭了老判据的顺风车。
const KNOWN_PIGGYBACK = [
  '### 3.9 一个正向标记，在它所标记的性质已经为假之后，仍然继续被写',
  '',
  '⚠️ **裁定：这一条不配机械判据。**',
  '',
  '**① X 长什么样**：略。',
  '**② X 打不红的那一刀**：略。',
  '**③ 什么会让答案改变**：略。',
  '',
  '#### ⚠️ 追记',
  '',
  '⚠️ **这一条追记本身不配机械判据。**（白嫖上面那三样，一个字没付）',
].join('\n')

test('锚：判据认得出「一节里两条豁免」——第二条白嫖了第一条付的三样', () => {
  assert.deepEqual(multipleExemptions(KNOWN_PIGGYBACK), [
    { heading: '### 3.9 一个正向标记，在它所标记的性质已经为假之后，仍然继续被写', count: 2 },
  ])
  // 同一份夹具上，**老判据是绿的**——这一行是上面那条注释的机械形式：
  // 少了它，这条新判据可以是在为老判据已经抓得住的东西再红一次。
  assert.deepEqual(unpaidExemptions(KNOWN_PIGGYBACK), [])
})

// ⭐ 反向锚：一节里**恰好一条**不许被误报。少了这条，判据可以退化成
// 「凡声明豁免就红」，那样它逼出来的不是「一节一条」，而是「别写豁免这两个字」
// ——与上面那条老判据的反向锚同一个理由、同一个形状。
test('锚：一节里恰好一条豁免时判据不报——它要的是一节一条，不是一条都不许有', () => {
  const single = ['### 3.9 标题', '', '⚠️ **裁定：这一条不配机械判据。**', '', '**① 略。**', '**② 略。**', '**③ 略。**'].join('\n')
  assert.deepEqual(multipleExemptions(single), [])
})

test('docs/16 §3 里没有哪一节声明了两条以上的「不配机械判据」', () => {
  assert.deepEqual(
    multipleExemptions(read(DOCS16)),
    [],
    'docs/16 的某个 §3.N 小节里出现了不止一条「不配机械判据」。\n' +
      '  上面那条判据按**小节**收：整节三样齐它就放行，于是第二条豁免会**白嫖**第一条付的三样。\n' +
      '  ⚠️ **修法不是把「不配机械判据」几个字删掉**——那只是把豁免藏起来，' +
      '与上面那条判据要防的是同一个错误修法。\n' +
      '  两条出路：**① 把第二条豁免另起一个 §3.N 小节**（那一节自己要付清三样，' +
      '上面那条判据就管得着它）；**② 去把抽取器真的扩成「按裁定收」**' +
      '（块切到下一条裁定为止），那时这一条就可以退休。\n' +
      '  ⚠️ 这条判据不假装能按裁定核——它让那个核不到的情形不可能发生，' +
      '理由写在 multipleExemptions() 上方，不在这里重复第二遍。',
  )
})

// ⚠️ 这两条真实文档判据的**零次迭代**由上面那条「前置条件」一起守着：
// numberedSections() 返回空集合时两者一起恒绿，而那条前置条件会先红。
// 抽取器本身另有一条锚（「只收编号过的 §3.N」）。三者不重复，各守一层。

// ⚠️ **盖不住的那一半，写清楚。**（这一条**有**机械判据，所以它不需要付那三样；
// 但它照样有盖不住的地方，照 `docs/16` §3 的家法写出来。）
//
// **① 认的是词，不是意思。** 有人用别的措辞下同一条裁定（「这条只能靠人读」
// 「不打算为它写测试」），`EXEMPTION` 这个串扫不到，判据一声不响。
// 这是开放集合，按词形穷举有结构性上限（`docs/16` §3.4），**不假装盖住了它**。
//
// **② 上面那条主判据按**小节**收，不按**裁定**收——这一点没变。** 它意味着一个小节里
// 的第二条豁免会**白嫖**第一条付的三样。把抽取器改成按裁定收（块切到「下一条裁定」
// 为止）仍然**没做**，代价与当初记下的一样：块边界要多一套规则，而那要去判断散落的
// ①②③ 归属哪一条豁免。
//
// ⚠️ **变的是那个情形现在被挡住了，不是抽取器变聪明了。** `multipleExemptions()`
// 要求每个编号小节至多一条豁免，于是「一节里两条」**根本到不了**主判据面前。
// **这一刀不假装判据能按裁定核**——它让核不到的那个情形不可能发生。
// 谁要加第二条豁免，只能另起一节（那一节自己要付三样，主判据管得着），
// 或者去把抽取器真的扩成按裁定收；那时这条限制就可以退休。
//
// ⚠️ **这一条的来历，按 §3.11 第 2 条把执行结果一起写下来**：M3b 把它从**预测**
// 变成了**实测**——往 §3.9 注入第二条「不配机械判据」而不付三样，
// 当时本文件**一条都不红**（同一刀注进没有豁免的 §3.12，主判据当场红；
// 两刀合起来才说明这个洞是真的）。控制方复跑确认，然后才有了上面那条判据。
// **写下它与堵上它中间隔了一轮**——记这一句是因为 `docs/16` §3.9 那条追记
// 说的正是这个节奏：一句「今天不值得」的保鲜期比写它的人以为的短。
//
// ⚠️ **另一处订正，留在这里不抹掉**：这一段原来写的是「今天 §3.9 / §3.10 各只有一条」
// ——**那张清单漏了 §3.8**。M3b 就地改成**不点名是哪几节**，理由是 `docs/16` §3.1：
// 写死的清单会漂，而这一处漂了之后的表现是**静默**（读的人按它以为只有两节要看，
// 而判据扫的是全部）。要知道今天是哪几节，重跑 `numberedSections()` 过滤一遍就有，
// **不必在这里抄一份**。
//
// **③ 只扫 `docs/16`。** 这条规矩今天只在 `docs/16` §3 生效。哪天别的文档也开始写
// 「不配机械判据」，这里要跟着扩——`DOCS16` 是个常量，扩它是一行的事，
// **但没人会因此被提醒**。
