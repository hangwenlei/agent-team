// 两张同族清单 ——「本轮没有做 X，而下一轮紧接着就做了 X」的实物清单，仓库里有两份：
// `docs/16` §3.9 的 M3b 追记，与 `docs/11` §5.23 修复轮 2 的收口块。
//
// 为什么需要这一份（M3d）：那两段正文自己逐字写着这件事——「两份各自可以被单独改，
// **而改了一边另一边不会有任何东西变红**」——并留了一条归属规则：「下一个往这张清单
// 加条目的人，负责把两份合成一份、或者写下为什么不合」。
//
// 本轮走的是第三条路：**不合并，给它写判据。** 两条理由：
//
//   ① 合并要从一个**带日期的收口块**里删正文，与 `docs/16` §3.6「原话不改」冲突；
//   ② **合并治的是「有两份拷贝」，而那条归属规则要治的毛病是「改一边另一边不会红」**
//      ——那是**没有判据**，不是**有两份拷贝**。合成一份之后，同一份知识照样会被
//      第二处引用，引用一样会过期，同族。
//
// ⚠️ **本判据钉的是条目数，不是条目内容。** 把一边某一条**改写成另一件事**，它全绿。
// 「逐条相等」这个更强的口径**今天用不了**：两张清单本来就不逐字相同（第 3 条两边
// 写的是不同的实物，第 1/2/4/5 条共享 commit 哈希而第 3 条两边都不带），那个口径
// **今天就红**。完整理由在 `docs/19` §9.4。
//
// 写法仿 `tests/plugin-name-sync.test.mjs`（「两个源头必须保持一致」的独立小文件）
// 与 `tests/readme-sync.test.mjs`（抽取器写成本文件内的具名函数，**主判据与自检锚
// 共用同一份**——`docs/16` §3.2：锚要钉在判据真正进入 assert 的那一层）。
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const read = (p) => readFileSync(new URL(`../${p}`, import.meta.url), 'utf8')

// 两张清单各自的定位锚。**锚在文件里必须恰好出现一次**——这一条是判据的一部分，
// 不是辅助：锚一旦撞上第二处，抠出来的就不是那张清单了，而条目数照样数得出来，
// 于是判据会在一段错误的文本上给出一个看着正常的答案（`docs/16` §3.2 那个形状）。
const LISTS = [
  {
    file: 'docs/16-M2b-裁定记录.md',
    where: 'docs/16 §3.9 的 M3b 追记',
    start: '按 §3.1 **列举，不报总数**——这条分支上的那几次：',
    end: '⚠️ **这张清单在仓库里有两份**',
  },
  {
    file: 'docs/11-M1b-遗留与已知边界.md',
    where: 'docs/11 §5.23 修复轮 2 的收口块',
    start: '**⚠️ `docs/16` §3.9 那个形状，在这条分支上已经不是偶发。按 §3.1 列举，不报总数：**',
    end: '> **不写总数**',
  },
]

// 抠出两个锚之间那一段。返回 `{ body }` 或 `{ err }`——**不抛**，让每条判据自己
// 决定怎么报，失败文案里才说得出是哪一头出的问题。
function blockOf(text, start, end) {
  const nStart = text.split(start).length - 1
  if (nStart !== 1) return { err: `起始锚在文件里出现 ${nStart} 次，要求恰好 1 次` }
  const s = text.indexOf(start) + start.length
  const rest = text.slice(s)
  const nEnd = rest.split(end).length - 1
  if (nEnd !== 1) return { err: `结束锚在起始锚之后出现 ${nEnd} 次，要求恰好 1 次` }
  return { body: rest.slice(0, rest.indexOf(end)) }
}

// 清单条目 = **顶格**的 `N. `。顶格这一条承重：两张清单的条目里都有缩进的续行与
// 嵌套段落，不要求顶格就会把它们也数进来。
function itemsOf(body) {
  return body.split(/\r?\n/).filter((l) => /^\d+\.\s/.test(l))
}

// ---------------------------------------------------------------------------
// 一、两头的锚各自抠得到，且抠出来的不是空段
// ---------------------------------------------------------------------------
//
// 这一条在主判据前面：主判据比的是两个数，**而两个都是 0 时它同样相等**。
// 没有这一条，把两张清单整段删掉是全绿的（`docs/16` §3.2 那条「零次断言」）。
for (const list of LISTS) {
  test(`锚：${list.where} 那张清单抠得出来，且条目数非零`, () => {
    const got = blockOf(read(list.file), list.start, list.end)
    assert.ok(
      !got.err,
      `${list.file} 里定位不到那张清单：${got.err}。\n` +
        `  本判据靠两个锚把 ${list.where} 那一段框出来。锚的原文被改动或删除，` +
        '这条就红——它红不代表清单错了，代表**这条判据已经不知道自己在看哪一段**。\n' +
        '  要动那一段的措辞，连本文件 LISTS 里的锚一起改；要删那张清单，' +
        '先去读 docs/19 §9.4，那里写着它为什么被钉住。',
    )
    assert.ok(
      itemsOf(got.body).length > 0,
      `${list.file} 的那张清单里一条顶格的「N. 」都没有。\n` +
        '  清单被清空、或者条目改成了别的排版（比如无序列表）。下面那条「两边条目数相等」' +
        '在两边都是 0 时照样绿，所以这一条必须单独站着。',
    )
  })
}

// ---------------------------------------------------------------------------
// 二、主判据：两张同族清单的条目数必须相等
// ---------------------------------------------------------------------------
test('两张同族清单的条目数必须相等——往一边加了条目而忘了另一边，这条红', () => {
  const counts = LISTS.map((list) => {
    const got = blockOf(read(list.file), list.start, list.end)
    assert.ok(!got.err, `${list.file}: ${got.err}（先看上面那条锚判据）`)
    return { where: list.where, file: list.file, n: itemsOf(got.body).length }
  })
  const [a, b] = counts
  assert.equal(
    a.n,
    b.n,
    `两张同族清单条目数对不上：${a.where} 有 ${a.n} 条，${b.where} 有 ${b.n} 条。\n` +
      '  这两张清单记的是同一件事的同一批实物，`docs/16` §3.9 与 `docs/11` §5.23 两段正文\n' +
      '  都逐字写着「两份各自可以被单独改，而改了一边另一边不会有任何东西变红」。\n' +
      '  **本条就是那句话的对策**：多半是往一边加了一条而忘了另一边。\n' +
      '  ⚠️ 它钉的是**条目数**，不是条目内容——两边的措辞本来就不同（第 3 条两边写的\n' +
      '  是不同的实物），所以不要为了让它绿而把两边改成逐字一样。\n' +
      '  为什么是「不合并、改成写判据」，在 `docs/19` §9.4 与 `docs/16` §3.9 的 M3d 追记里。',
  )
})

// ---------------------------------------------------------------------------
// 三、⭐ 正向自检锚：钉两个抽取器本身，钉在合成样本上
// ---------------------------------------------------------------------------
//
// `docs/16` §3.2：锚要钉在判据**真正进入 assert 的那一层**。上面两条判据的全部分量
// 都压在 `blockOf` + `itemsOf` 上，所以这两个函数要各自证明三件事：
//
//   · `blockOf` **停在结束锚**（否则它会一路吃到文件末尾，把别处的编号列表数进来）；
//   · `blockOf` 在**锚不唯一**时报错，而不是闷头取第一处；
//   · `itemsOf` **只认顶格**，缩进的续行与嵌套编号不算条目。
test('自检：blockOf() 停在结束锚、锚不唯一时报错，itemsOf() 只认顶格条目', () => {
  const sample = [
    '前言：这一行不含起始锚，否则下面第一条就该红（而它确实红过一次）',
    'START',
    '1. 甲',
    '   1. 这是嵌套的，不算一条',
    '   续行也不算',
    '2. 乙',
    'END',
    '3. 结束锚之后的，不该被数进来',
  ].join('\r\n')

  const got = blockOf(sample, 'START', 'END')
  assert.ok(!got.err, `合成样本上 blockOf 就该成功，却报了：${got.err}`)
  assert.deepEqual(itemsOf(got.body), ['1. 甲', '2. 乙'])

  // 停在结束锚：样本里 END 之后还有一条顶格条目，它一旦被数进来就是 3
  assert.equal(itemsOf(got.body).length, 2)

  // 锚不唯一 → 报错，而不是静悄悄取第一处。
  // ⚠️ **两个样本要各自只犯一种毛病。** 初稿这里用的样本同时有两个 START 和两个 END，
  // 于是「起始锚必须唯一」那一格被「结束锚必须唯一」那一格顺带兜住了——把前者放宽成
  // `nStart < 1`，这条自检照样绿（变异实测，存活）。这正是 `docs/16` §3.12 那个形状：
  // 洞不长在判据的缝里，长在两条判据之间。
  const dupStart = ['START', '1. 甲', 'START', '9. 丙', 'END'].join('\r\n')
  assert.ok(blockOf(dupStart, 'START', 'END').err, '起始锚出现两次时 blockOf 必须报错')
  const dupEnd = ['START', '1. 甲', 'END', '9. 丙', 'END'].join('\r\n')
  assert.ok(blockOf(dupEnd, 'START', 'END').err, '结束锚出现两次时 blockOf 必须报错')
  assert.ok(blockOf(sample, '不存在的锚', 'END').err, '起始锚找不到时 blockOf 必须报错')
  assert.ok(blockOf(sample, 'START', '不存在的锚').err, '结束锚找不到时 blockOf 必须报错')

  // LF 与 CRLF 两种行尾都要认得——本仓库的换行符是混的（`docs/11` §5.28）
  assert.deepEqual(itemsOf('1. 甲\n2. 乙'), ['1. 甲', '2. 乙'])
  assert.deepEqual(itemsOf('1. 甲\r\n2. 乙'), ['1. 甲', '2. 乙'])
})
