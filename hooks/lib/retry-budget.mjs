// 「平台对 `SubagentStop` 的拒绝重试多少次才静默放行」——这份知识的**单一真源**。
//
// 这个文件存在的全部理由：同一份知识此前在**八句话、六个文件**里各写了一份
// （`hooks/gate.mjs` 的 H5a 告警正文、`hooks/lib/deliverable.mjs` 两处、
// `hooks/lib/deny.mjs`、`stages.README.md`、`tests/deliverable.test.mjs`、
// `tests/gate-deliverable.test.mjs`、`tests/gate-dispatch.test.mjs`），
// 而它们**互不共享词形**：五句写的是中文数字（「九次」「约九次」「最多九次」），
// 三句写的是 ASCII（「约 9 次」）。**按词形扫一遍只能捞到一半**——`docs/16` §3.4
// 说的那个上限，这是它的又一件实物。逐句与成因记在 `docs/11` §5.29。
//
// ---------------------------------------------------------------------------
// 【这个数是多少】**它不是一个常数，所以这里不写一个数，写的是区间与数法。**
// ---------------------------------------------------------------------------
//
// 本仓库对「平台在静默放行之前把 subagent 顶回去多少次」有**四次观测**，
// 落在 **8 / 8 / 9 / 10** 上，而且**四次数的不是同一个东西**：
//
//   · `docs/07` §1.2 第二轮（N=15，2026-09-16）：**9**
//     —— hook 自己的计数日志，9 行全是 exit 2，第 10 行没有。
//   · `docs/12` §7.1：**8**
//     —— 子代理自己的 `tool_uses: 8`，一个没人设计的场景里自发拦截。
//   · `docs/13`（hook-a 探针，M1c）：**8**
//     —— `at-backend` 被顶 8 次才由平台放弃。
//   · `docs/19` §11.4.6（远端安装，CLI 2.1.278，2026-09-21）：**10**
//     —— 平台写进子代理转录的 `Stop hook feedback` 条数。
//
// 三种数法各自可以差一格：`tool_uses` 天然 ≤ 拦截次数（最后一次拦截未必再引出
// 一次工具调用），hook 计数由 hook 自己写、转录条数由平台自己写。
// **所以 8→10 这个差既可能是平台的真实抖动，也可能是数法的产物——两者本轮没有
// 分开**，什么会分开它写在 `docs/11` §5.29。
//
// ⚠️ 「它是 10」「约 10」「至少 10」这三句话，这里**一句都不写**：
// 前两句要丢掉 8/8/9 那三次观测，第三句被 8 和 9 当场证伪。逐句理由见 §5.29。
// ⚠️ 而**最要紧的一条是**：这个数在上面八句话里**没有一句是承重的**——
// 读到它的人该做的事（去 run 目录核实产物在不在）不随 8 还是 10 而变。
// 所以别处该写的不是这个数，是**指向本文件**。
//
// ---------------------------------------------------------------------------
// 【判据】`tests/retry-budget-single-source.test.mjs`
// ---------------------------------------------------------------------------
